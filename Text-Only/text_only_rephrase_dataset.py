import argparse
import json
import os
import sys

import torch

from transformers import AutoProcessor, LlavaForConditionalGeneration

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_ROOT not in sys.path:
    sys.path.insert(0, _REPO_ROOT)

from text_only_phrase_attention import (
    _pick_model_input_device,
    _locate_rel_phrase_token_positions,
    _locate_span,
    _token_labels_for_positions,
    compute_phrase_to_caption_attention,
    plot_phrase_to_caption,
)


MODEL_ID = "llava-hf/llava-1.5-7b-hf"


def _read_jsonl(path: str) -> list[dict]:
    rows = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
    return rows


def build_context_prompt(context: str, question: str) -> str:
    return (
        "You are given a short context statement.\n"
        "Use only the context as evidence.\n"
        "Answer the question with only \"yes\" or \"no\".\n\n"
        f"Context: {context}\n\n"
        f"Question: {question}\n"
        "Answer:"
    )


def _move_to_device(batch: dict, device: torch.device) -> dict:
    out = {}
    for k, v in batch.items():
        out[k] = v.to(device) if hasattr(v, "to") else v
    return out


def _get_yesno_from_generated_text(s: str) -> str:
    s = (s or "").strip().lower()
    if s.startswith("yes"):
        return "yes"
    if s.startswith("no"):
        return "no"
    if " yes" in f" {s}":
        return "yes"
    if " no" in f" {s}":
        return "no"
    return "unknown"


def _get_yesno_from_scores(outputs, tokenizer) -> tuple[str | None, float | None, float | None]:
    scores = getattr(outputs, "scores", None)
    if not scores:
        return None, None, None

    first_token_logits = scores[0][0]
    probs = torch.softmax(first_token_logits, dim=-1)

    yes_variants = ["Yes", " yes", "yes"]
    no_variants = ["No", " no", "no"]

    def _token_ids(variants: list[str]) -> set[int]:
        ids: set[int] = set()
        for s in variants:
            enc = tokenizer.encode(s, add_special_tokens=False)
            if enc:
                ids.add(int(enc[-1]))
        return ids

    yes_ids = _token_ids(yes_variants)
    no_ids = _token_ids(no_variants)

    p_yes = float(sum(probs[t].item() for t in yes_ids if t < probs.numel()))
    p_no = float(sum(probs[t].item() for t in no_ids if t < probs.numel()))

    denom = p_yes + p_no
    if denom <= 0:
        return None, None, None

    p_yes_n = p_yes / denom
    p_no_n = p_no / denom
    pred = "yes" if p_yes_n >= p_no_n else "no"
    return pred, p_yes_n, p_no_n


def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="Run text-only relational QA and analyze attention.")
    ap.add_argument(
        "--input_jsonl",
        type=str,
        default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "text_only_relphrase_qa.jsonl"),
        help="Input JSONL generated by text_only_relphrase_dataset.py",
    )
    ap.add_argument(
        "--out_dir",
        type=str,
        default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "vis_results"),
        help="Output directory for summaries and plots.",
    )
    ap.add_argument("--model_id", type=str, default=MODEL_ID)
    ap.add_argument("--max_examples", type=int, default=None)
    ap.add_argument(
        "--plot_examples",
        type=int,
        default=5,
        help="Number of examples to plot (phrase->context attention).",
    )
    return ap.parse_args()


def main() -> None:
    args = parse_args()

    rows = _read_jsonl(args.input_jsonl)
    if not rows:
        raise SystemExit(f"No rows found in: {args.input_jsonl}")

    os.makedirs(args.out_dir, exist_ok=True)

    print(f"Loading model: {args.model_id}")
    if torch.cuda.is_available():
        model = LlavaForConditionalGeneration.from_pretrained(
            args.model_id,
            torch_dtype=torch.float16,
            device_map="auto",
            attn_implementation="eager",
        )
    else:
        model = LlavaForConditionalGeneration.from_pretrained(
            args.model_id,
            torch_dtype=torch.float32,
            device_map=None,
            attn_implementation="eager",
        )
        model = model.to("cpu")
    processor = AutoProcessor.from_pretrained(args.model_id)
    tokenizer = processor.tokenizer
    model.eval()

    max_n = args.max_examples or len(rows)
    summary_path = os.path.join(args.out_dir, "summary.jsonl")
    metrics_path = os.path.join(args.out_dir, "metrics.json")

    num_total = 0
    num_correct = 0

    with open(summary_path, "w", encoding="utf-8") as f:
        for i, row in enumerate(rows[:max_n]):
            context = (row.get("context") or "").strip()
            question = (row.get("question") or "").strip()
            answer = (row.get("answer") or "").strip().lower()
            rel_phrase = (row.get("rel_phrase") or "").strip()

            if not context or not question or not rel_phrase:
                raise SystemExit(f"Missing context/question/rel_phrase at row {i}")

            prompt = build_context_prompt(context, question)
            tok = tokenizer(prompt, return_tensors="pt")
            model_device = _pick_model_input_device(model)
            tok = _move_to_device(tok, model_device)

            full_ids = tok["input_ids"][0]
            full_ids_list = full_ids.detach().cpu().tolist()

            context_positions = _locate_span(tokenizer, full_ids_list, context)
            phrase_positions = _locate_rel_phrase_token_positions(
                tokenizer, full_ids, question_text=question, rel_phrase=rel_phrase
            )

            if not context_positions:
                raise SystemExit(f"Could not locate context span for row {i}")
            if not phrase_positions:
                raise SystemExit(f"Could not locate rel_phrase tokens for row {i}: '{rel_phrase}'")

            # Get attention scores (phrase -> context)
            stats = compute_phrase_to_caption_attention(
                model=model,
                tokenizer=tokenizer,
                input_ids=tok["input_ids"],
                attention_mask=tok.get("attention_mask"),
                phrase_positions=phrase_positions,
                caption_positions=context_positions,
            )

            # Generate answer
            with torch.no_grad():
                gen = model.generate(
                    **tok,
                    max_new_tokens=5,
                    do_sample=False,
                    return_dict_in_generate=True,
                    output_scores=True,
                )
            decoded = tokenizer.decode(gen.sequences[0], skip_special_tokens=True)
            # Response is at the end; keep it simple
            pred_text = decoded.split("Answer:", 1)[-1].strip()
            pred = _get_yesno_from_generated_text(pred_text)
            score_pred, p_yes, p_no = _get_yesno_from_scores(gen, tokenizer)
            if score_pred is not None:
                pred = score_pred

            is_correct = pred == answer
            num_total += 1
            num_correct += int(is_correct)

            context_tok_labels = _token_labels_for_positions(tokenizer, full_ids_list, context_positions)
            phrase_tok_labels = _token_labels_for_positions(tokenizer, full_ids_list, phrase_positions)

            record = {
                "index": i,
                "context": context,
                "question": question,
                "answer": answer,
                "prediction": pred,
                "is_correct": is_correct,
                "rel_phrase": rel_phrase,
                "context_token_positions": context_positions,
                "phrase_token_positions": phrase_positions,
                "context_tokens": context_tok_labels,
                "phrase_tokens": phrase_tok_labels,
                "token_scores_mean": stats["mean"].tolist(),
                "p_yes": p_yes,
                "p_no": p_no,
            }
            f.write(json.dumps(record) + "\n")

            if i < args.plot_examples:
                ex_dir = os.path.join(args.out_dir, f"example_{i:03d}")
                title_prefix = f"Phrase→Context | '{rel_phrase}'"
                plot_phrase_to_caption(
                    out_dir=ex_dir,
                    caption_tokens=context_tok_labels,
                    phrase_tokens=phrase_tok_labels,
                    scores_per_layer=stats["per_layer"],
                    scores_mean=stats["mean"],
                    title_prefix=title_prefix,
                )

    metrics = {
        "input_jsonl": args.input_jsonl,
        "num_total": num_total,
        "num_correct": num_correct,
        "accuracy": (num_correct / num_total) if num_total else 0.0,
    }
    with open(metrics_path, "w", encoding="utf-8") as f:
        json.dump(metrics, f, indent=2)

    print(f"Wrote summary to: {summary_path}")
    print(f"Wrote metrics to: {metrics_path}")


if __name__ == "__main__":
    main()
